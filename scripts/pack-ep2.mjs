// Packs Canale Viola (hub + Ep.2 game + the audio cut) into encrypted blobs.
// Source HTML lives outside git (.superpowers/affari-tuoi-prototype.html); the key is derived
// from the secret path token in the printed link (.superpowers/canale-token.txt), also outside git.
// The repo only ever holds ciphertext.   Run after editing the source:  node scripts/pack-ep2.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
const { subtle } = globalThis.crypto;

const token = readFileSync('.superpowers/canale-token.txt', 'utf8').trim();
const html = readFileSync('.superpowers/affari-tuoi-prototype.html', 'utf8');
const audio = readFileSync('.superpowers/media/vz-crotone.m4a');

const enc = new TextEncoder();
const salt = crypto.getRandomValues(new Uint8Array(16));
const base = await subtle.importKey('raw', enc.encode(token), 'PBKDF2', false, ['deriveKey']);
const key = await subtle.deriveKey({ name: 'PBKDF2', salt, iterations: 100000, hash: 'SHA-256' }, base, { name: 'AES-GCM', length: 256 }, false, ['encrypt']);
const seal = async (bytes) => {
  const iv = crypto.getRandomValues(new Uint8Array(12));
  const ct = new Uint8Array(await subtle.encrypt({ name: 'AES-GCM', iv }, key, bytes));
  return { iv, ct };
};
const b64 = (u8) => Buffer.from(u8).toString('base64');

const page = await seal(enc.encode(html.replace('__CANALE_SALT__', b64(salt))));
writeFileSync('src/viola/canale.enc.js',
  `// Generated by scripts/pack-ep2.mjs. Ciphertext only; do not edit.\nexport default ${JSON.stringify({ salt: b64(salt), iv: b64(page.iv), ct: b64(page.ct) })};\n`);

// audio: binary file = 12-byte iv + ciphertext, same key
const a = await seal(audio);
mkdirSync('public/media', { recursive: true });
writeFileSync('public/media/vz.bin', Buffer.concat([Buffer.from(a.iv), Buffer.from(a.ct)]));

// token check: a tiny marker encrypted under the same slow-derived key. Checking a token means
// deriving the key (100k PBKDF2 rounds) and trying to decrypt it; there is no fast hash to attack.
const gate = await seal(enc.encode('canale'));
writeFileSync('src/viola/token.js', `// Generated by scripts/pack-ep2.mjs. Salt and an encrypted marker; the token itself is not in the repo.\nexport const SALT = '${b64(salt)}';\nexport const GATE = ${JSON.stringify({ iv: b64(gate.iv), ct: b64(gate.ct) })};\n`);
console.log(`packed: page ${page.ct.length} bytes, audio ${a.ct.length} bytes`);
